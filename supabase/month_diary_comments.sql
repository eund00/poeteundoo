create table if not exists public.month_diary_comments (
  id bigint generated by default as identity primary key,
  diary_id bigint not null
    references public.month_diaries(id) on delete cascade,
  nickname text not null
    check (length(btrim(nickname)) between 1 and 24),
  content text not null
    check (length(btrim(content)) between 1 and 1000),
  password_salt uuid not null,
  password_hash text not null
    check (password_hash ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now()
);

create index if not exists month_diary_comments_diary_created_idx
  on public.month_diary_comments (diary_id, created_at);

alter table public.month_diary_comments enable row level security;
revoke all on public.month_diary_comments from public, anon, authenticated;
grant select (id, diary_id, nickname, content, created_at, password_salt)
  on public.month_diary_comments to anon, authenticated;

drop policy if exists "Anyone can read published month diary comments"
  on public.month_diary_comments;
create policy "Anyone can read published month diary comments"
  on public.month_diary_comments
  for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.month_diaries as diary
      where diary.id = month_diary_comments.diary_id
        and diary.is_published = true
    )
  );

create or replace function public.add_month_diary_comment(
  p_diary_id bigint,
  p_nickname text,
  p_content text,
  p_password_salt uuid,
  p_password_hash text
)
returns table (id bigint, nickname text, content text, created_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_nickname text := pg_catalog.btrim(p_nickname);
  normalized_content text := pg_catalog.btrim(p_content);
begin
  if p_diary_id is null
    or normalized_nickname is null
    or normalized_content is null
    or p_password_salt is null
    or p_password_hash is null
  then
    raise exception 'Diary, nickname, comment, and password are required.'
      using errcode = '22023';
  end if;

  if pg_catalog.char_length(normalized_nickname) not between 1 and 24 then
    raise exception 'Nickname must be between 1 and 24 characters.'
      using errcode = '22023';
  end if;

  if pg_catalog.char_length(normalized_content) not between 1 and 1000 then
    raise exception 'Comment must be between 1 and 1000 characters.'
      using errcode = '22023';
  end if;

  if p_password_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Password hash is invalid.'
      using errcode = '22023';
  end if;

  if not exists (
    select 1
    from public.month_diaries as diary
    where diary.id = p_diary_id
      and diary.is_published = true
  ) then
    raise exception 'Published diary not found.'
      using errcode = 'P0002';
  end if;

  return query
  insert into public.month_diary_comments as inserted (
    diary_id,
    nickname,
    content,
    password_salt,
    password_hash
  )
  values (
    p_diary_id,
    normalized_nickname,
    normalized_content,
    p_password_salt,
    p_password_hash
  )
  returning
    inserted.id,
    inserted.nickname,
    inserted.content,
    inserted.created_at;
end;
$$;

create or replace function public.manage_month_diary_comment(
  p_action text,
  p_comment_id bigint,
  p_password_hash text,
  p_new_content text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_password_hash text;
  normalized_content text := pg_catalog.btrim(p_new_content);
begin
  if p_action is null
    or p_action not in ('edit', 'delete')
    or p_comment_id is null
    or p_password_hash is null
    or p_password_hash !~ '^[0-9a-f]{64}$'
  then
    raise exception 'Invalid comment management request.'
      using errcode = '22023';
  end if;

  select c.password_hash
  into stored_password_hash
  from public.month_diary_comments as c
  where c.id = p_comment_id;

  if not found or stored_password_hash <> p_password_hash then
    return false;
  end if;

  if p_action = 'edit' then
    if normalized_content is null
      or pg_catalog.char_length(normalized_content) not between 1 and 1000
    then
      raise exception 'Comment must be between 1 and 1000 characters.'
        using errcode = '22023';
    end if;

    update public.month_diary_comments as c
    set content = normalized_content
    where c.id = p_comment_id;
  else
    delete from public.month_diary_comments as c
    where c.id = p_comment_id;
  end if;

  return true;
end;
$$;

revoke all on function public.add_month_diary_comment(bigint, text, text, uuid, text)
  from public;
grant execute on function public.add_month_diary_comment(bigint, text, text, uuid, text)
  to anon, authenticated;
revoke all on function public.manage_month_diary_comment(text, bigint, text, text)
  from public;
grant execute on function public.manage_month_diary_comment(text, bigint, text, text)
  to anon, authenticated;

comment on table public.month_diary_comments is
  'Public comments for published monthly diary entries.';

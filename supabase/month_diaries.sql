create table if not exists public.month_diaries (
  id bigint generated by default as identity primary key,
  title text not null check (length(btrim(title)) > 0),
  diary_date date not null,
  body_html text not null check (length(btrim(body_html)) > 0),
  background_image text,
  card_excerpt text,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.month_diaries
  add column if not exists background_image text;
alter table public.month_diaries
  add column if not exists card_excerpt text;

create table if not exists public.month_diary_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.month_diary_admins enable row level security;
alter table public.month_diaries enable row level security;

revoke all on public.month_diary_admins from anon, authenticated;
grant select on public.month_diaries to anon;
grant select, insert, update, delete on public.month_diaries to authenticated;
grant usage, select on sequence public.month_diaries_id_seq to authenticated;

create or replace function public.is_month_diary_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.month_diary_admins
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_month_diary_admin() from public;
grant execute on function public.is_month_diary_admin() to authenticated;

drop policy if exists "Anyone can read published month diaries"
  on public.month_diaries;
create policy "Anyone can read published month diaries"
  on public.month_diaries
  for select
  to anon, authenticated
  using (is_published = true);

drop policy if exists "Authenticated users can manage month diaries"
  on public.month_diaries;
create policy "Month diary admins can manage month diaries"
  on public.month_diaries
  for all
  to authenticated
  using (public.is_month_diary_admin())
  with check (public.is_month_diary_admin());

insert into storage.buckets (id, name, public)
values ('month-diary-images', 'month-diary-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Anyone can read month diary images"
  on storage.objects;
create policy "Anyone can read month diary images"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'month-diary-images');

drop policy if exists "Month diary admins can upload images"
  on storage.objects;
create policy "Month diary admins can upload images"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'month-diary-images'
    and public.is_month_diary_admin()
  );

